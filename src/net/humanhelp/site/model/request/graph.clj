(defn request-document
  "Returns one current Request document by UUID, or nil."
  [ctx request-id]
  (when
   (uuid?
    request-id)
    (model/load-by-id
     request.schema/request-descriptor
     ctx
     request-id)))

(defn request-assignment-document
  "Returns one current RequestAssignment document by UUID, or nil."
  [ctx assignment-id]
  (when
   (uuid?
    assignment-id)
    (model/load-by-id
     request.schema/request-assignment-descriptor
     ctx
     assignment-id)))

;; =============================================================================
;; Request Assignment collections
;; =============================================================================

(defn- assignments-for-request-where
  [request-id include-ended?]
  (cond->
   [:and
    [:= :request-assignment/request
     request-id]]

    (not
     include-ended?)
    (conj
     [:= :request-assignment/status
      [:lift :active]])))

(defn- assignment-order
  [assignments]
  (->>
   assignments

   (sort-by
    (juxt
     :request-assignment/created-at
     :xt/id))

   vec))

(defn assignments-for-request
  "Returns every current RequestAssignment belonging to Request.

   Results include ended historical assignments and are ordered oldest first,
   with assignment UUID as deterministic tiebreaker."
  [ctx request-id]
  (if
   (uuid?
    request-id)
    (assignment-order
     (rows
      request.schema/request-assignment-descriptor
      ctx
      {:select
       request-assignment-document-columns

       :from
       [request/assignment-entity-type]

       :where
       (assignments-for-request-where
        request-id
        true)}))
    []))

(defn active-assignments-for-request
  "Returns all active RequestAssignments belonging to Request.

   Results are ordered oldest first."
  [ctx request-id]
  (if
   (uuid?
    request-id)
    (assignment-order
     (rows
      request.schema/request-assignment-descriptor
      ctx
      {:select
       request-assignment-document-columns

       :from
       [request/assignment-entity-type]

       :where
       (assignments-for-request-where
        request-id
        false)}))
    []))

(defn active-assignment-for-helper
  "Returns helper-id's one active assignment on Request, or nil.

   Multiple active assignments for the same helper and Request are persisted
   corruption and fail loudly."
  [ctx request-id helper-id]
  (if
   (and
    (uuid?
     request-id)

    (uuid?
     helper-id))
    (let [matches
          (rows
           request.schema/request-assignment-descriptor
           ctx
           {:select
            request-assignment-document-columns

            :from
            [request/assignment-entity-type]

            :where
            [:and
             [:= :request-assignment/request
              request-id]

             [:= :request-assignment/helper
              helper-id]

             [:= :request-assignment/status
              [:lift :active]]]})]
      (case
       (count
        matches)

        0
        nil

        1
        (first
         matches)

        (fail!
         :request.graph/non-unique-active-helper-assignment
         "More than one active RequestAssignment exists for the helper."
         {:request/id
          request-id

          :request-assignment/helper
          helper-id

          :request-assignment/ids
          (mapv
           request/assignment-id
           matches)})))
    nil))

(defn active-primary-assignment-for-request
  "Returns Request's one active primary RequestAssignment, or nil.

   Multiple active primary assignments are persisted corruption."
  [ctx request-id]
  (if
   (uuid?
    request-id)
    (let [matches
          (rows
           request.schema/request-assignment-descriptor
           ctx
           {:select
            request-assignment-document-columns

            :from
            [request/assignment-entity-type]

            :where
            [:and
             [:= :request-assignment/request
              request-id]

             [:= :request-assignment/role
              [:lift :primary]]

             [:= :request-assignment/status
              [:lift :active]]]})]
      (case
       (count
        matches)

        0
        nil

        1
        (first
         matches)

        (fail!
         :request.graph/non-unique-active-primary
         "More than one active primary RequestAssignment exists."
         {:request/id
          request-id

          :request-assignment/ids
          (mapv
           request/assignment-id
           matches)})))
    nil))

;; =============================================================================
;; Location Request collections
;; =============================================================================

(def active-request-predicate
  [:or
   [:= :request/status
    [:lift :open]]

   [:= :request/status
    [:lift :claimed]]

   [:= :request/status
    [:lift :on-the-way]]])

(defn- requests-for-location-where
  [organization-id location-id include-terminal?]
  (cond->
   [:and
    [:= :request/organization
     organization-id]

    [:= :request/location
     location-id]]

    (not
     include-terminal?)
    (conj
     active-request-predicate)))

(defn- newest-request-first
  [left right]
  (let [created-comparison
        (compare
         (:request/created-at
          right)

         (:request/created-at
          left))]
    (if
     (zero?
      created-comparison)
      (compare
       (:xt/id
        right)

       (:xt/id
        left))

      created-comparison)))

(defn requests-for-location
  "Returns the canonical Request collection for one Organization Location.

   input:

     {:organization-id   uuid
      :location-id       uuid
      :include-terminal? boolean}

   Terminal Requests are excluded unless :include-terminal? is exactly true.

   Results are newest first with Request UUID as deterministic tiebreaker.

   This function establishes only persisted Request ownership fields. It does
   not prove that Organization or Location currently exists or is operational;
   those facts belong to Organization."
  [ctx {:keys
        [organization-id
         location-id
         include-terminal?]}]
  (if
   (and
    (uuid?
     organization-id)

    (uuid?
     location-id))
    (->>
     (rows
      request.schema/request-descriptor
      ctx
      {:select
       request-document-columns

       :from
       [request/request-entity-type]

       :where
       (requests-for-location-where
        organization-id
        location-id
        (true?
         include-terminal?))})

     (sort
      newest-request-first)

     vec)
    []))

;; =============================================================================
;; Active-assignment consistency
;; =============================================================================

(defn- require-assignment-for-request!
  [request-document assignment]
  (request/require-assignment-document
   assignment)

  (when-not
   (request/assignment-for-request?
    assignment
    (request/request-id
     request-document))
    (fail!
     :request.graph/assignment-request-mismatch
     "A Request snapshot contains an assignment belonging to another Request."
     {:request/id
      (request/request-id
       request-document)

      :request-assignment/id
      (request/assignment-id
       assignment)

      :request-assignment/request
      (request/assignment-request-id
       assignment)}))

  (when-not
   (request/assignment-active?
    assignment)
    (fail!
     :request.graph/inactive-assignment-in-active-set
     "A Request active-assignment read returned an ended assignment."
     {:request/id
      (request/request-id
       request-document)

      :request-assignment/id
      (request/assignment-id
       assignment)

      :request-assignment/status
      (request/assignment-status
       assignment)}))

  assignment)

(defn- require-distinct-active-helpers!
  [request-document assignments]
  (let [helper-ids
        (mapv
         request/assignment-helper-id
         assignments)

        distinct-helper-ids
        (set
         helper-ids)]
    (when-not
     (=
      (count
       helper-ids)

      (count
       distinct-helper-ids))
      (fail!
       :request.graph/duplicate-active-helper
       "A helper has more than one active RequestAssignment."
       {:request/id
        (request/request-id
         request-document)

        :request-assignment/helper-ids
        helper-ids})))

  assignments)

(defn- require-lifecycle-assignment-consistency!
  [request-document assignments]
  (let [primary
        (request/active-primary-assignment
         assignments)]

    (cond
      (request/open?
       request-document)
      (when
       (seq
        assignments)
        (fail!
         :request.graph/open-request-has-active-assignments
         "An open Request must not have active RequestAssignments."
         {:request/id
          (request/request-id
           request-document)

          :request/active-assignment-ids
          (mapv
           request/assignment-id
           assignments)}))

      (request/lifecycle-expects-primary-assignment?
       request-document)
      (when-not
       primary
        (fail!
         :request.graph/missing-active-primary
         "The Request lifecycle requires an active primary RequestAssignment."
         {:request/id
          (request/request-id
           request-document)

          :request/status
          (request/request-status
           request-document)}))

      (request/terminal?
       request-document)
      (when
       (seq
        assignments)
        (fail!
         :request.graph/terminal-request-has-active-assignments
         "A terminal Request must not have active RequestAssignments."
         {:request/id
          (request/request-id
           request-document)

          :request/status
          (request/request-status
           request-document)

          :request/active-assignment-ids
          (mapv
           request/assignment-id
           assignments)})))

    primary))

(defn- active-assignment-state
  [request-document assignments]
  (request/require-request-document
   request-document)

  (let [assignments
        (mapv
         #(require-assignment-for-request!
           request-document
           %)
         assignments)

        _
        (require-distinct-active-helpers!
         request-document
         assignments)

        primary
        (require-lifecycle-assignment-consistency!
         request-document
         assignments)]

    {:assignments
     assignments

     :primary-assignment
     primary

     :active-helper-ids
     (request/active-helper-ids
      assignments)

     :active-collaborator-helper-ids
     (request/active-collaborator-helper-ids
      assignments)}))

