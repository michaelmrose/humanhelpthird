(defn request-snapshot-from-document
  "Builds Request's authoritative Request-owned active-assignment snapshot from
   an already-loaded Request document.

   The returned state is internally consistent across the Request and all
   current active RequestAssignments.

   This does not establish Organization scope state or helper authorization."
  [ctx request-document]
  (request/require-request-document
   request-document)

  (let [assignments
        (active-assignments-for-request
         ctx
         (request/request-id
          request-document))

        {:keys
         [primary-assignment
          active-helper-ids
          active-collaborator-helper-ids]}
        (active-assignment-state
         request-document
         assignments)]

    {:request
     request-document

     :assignments
     assignments

     :primary-assignment
     primary-assignment

     :active-helper-ids
     active-helper-ids

     :active-collaborator-helper-ids
     active-collaborator-helper-ids}))

(defn request-snapshot
  "Returns Request plus its authoritative active RequestAssignment state.

   Returns nil when Request does not exist.

   A present Request with inconsistent Request-owned assignment state is an
   error rather than a partial snapshot."
  [ctx request-id]
  (when-let [request-document
             (request-document
              ctx
              request-id)]
    (request-snapshot-from-document
     ctx
     request-document)))

(defn require-request-snapshot
  "Returns Request's current Request-owned snapshot or throws when Request does
   not exist."
  [ctx request-id]
  (or
   (request-snapshot
    ctx
    request-id)

   (fail!
    :request/not-found
    "The Request does not exist."
    {:request/id
     request-id})))

;; =============================================================================
;; Location snapshots
;; =============================================================================

(defn request-snapshots-for-location
  "Returns canonical Location Requests enriched only with Request-owned active
   assignment state.

   Organization hierarchy, operational state, Memberships, helper roles, and
   User display data are deliberately absent."
  [ctx input]
  (mapv
   #(request-snapshot-from-document
     ctx
     %)
   (requests-for-location
    ctx
    input)))

