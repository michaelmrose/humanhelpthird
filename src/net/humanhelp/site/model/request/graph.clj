(def request-assignment-summary-query
  [[:? :request/has-primary-assignment?]
   [:? :request/primary-assignment-id]
   [:? :request/primary-helper-id]
   [:? :request/active-helper-ids]
   [:? :request/active-collaborator-helper-ids]])

(def request-assignment-summary-resolver
  (graph/resolver
   {:id
    ::request-assignment-summary

    :input
    [{:request/doc
      request-document-query}]

    :output
    request-assignment-summary-query

    :resolve-fn
    (fn [ctx
         {:request/keys
          [doc]}]
      (let [{:keys
             [primary-assignment
              active-helper-ids
              active-collaborator-helper-ids]}
            (request-snapshot-from-document
             ctx
             doc)]

        (cond->
         {:request/has-primary-assignment?
          (boolean
           primary-assignment)

          :request/active-helper-ids
          active-helper-ids

          :request/active-collaborator-helper-ids
          active-collaborator-helper-ids}

          primary-assignment
          (assoc
           :request/primary-assignment-id
           (request/assignment-id
            primary-assignment)

           :request/primary-helper-id
           (request/assignment-helper-id
            primary-assignment)))))}))

