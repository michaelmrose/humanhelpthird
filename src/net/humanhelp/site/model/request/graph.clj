(ns net.humanhelp.site.model.request.graph
  "Request-specific read composition.

   gesso.model owns ordinary persisted-document loading and generated by-ID and
   field resolvers for both Request and RequestAssignment.

   This namespace owns only Request-specific reads that require composition
   across Request-owned documents:

   - Request Assignments for one Request;
   - active Assignment lookup and uniqueness;
   - canonical Request collections for one Location;
   - Request + active-Assignment snapshots;
   - cross-document lifecycle/Assignment consistency;
   - derived Request and RequestAssignment Graph facts.

   This namespace does not load or interpret User, Membership, Invitation, or
   Organization documents. Those models remain available only through their
   public cores to Request FX."
  (:require
   [com.biffweb.graph :as graph]
   [com.biffweb.xtdb :as biff.xtdb]
   [gesso.model.core :as model]
   [gesso.model.schema :as model.schema]
   [net.humanhelp.site.model.request.domain :as request]
   [net.humanhelp.site.model.request.schema :as request.schema]))

