;; =============================================================================
;; Errors
;; =============================================================================

(defn- fail!
  [type message details]
  (throw
   (ex-info
    message
    {:error/type
     type

     :error/details
     details})))

;; =============================================================================
;; Persistence normalization
;; =============================================================================

(defn- malli-options
  [ctx]
  (or
   (:biff/malli-opts
    ctx)

   {}))

(defn- normalize-loaded-document
  [descriptor ctx document]
  (when
   document
    (model.schema/normalize-and-validate
     (:document-schema
      descriptor)

     document

     {:codec-overrides
      (get-in
       descriptor
       [:persistence
        :codec-overrides])

      :malli-options
      (malli-options
       ctx)})))

(defn- query-context!
  [ctx]
  (if
   (and
    (map? ctx)
    (or
     (:biff.xtdb/connection-pool ctx)
     (:biff.xtdb/node ctx)))
    ctx

    (fail!
     :request.graph/missing-biff-connection
     "Request reads require Biff 2 XTDB context with :biff.xtdb/connection-pool or :biff.xtdb/node."
     {:ctx-keys
      (when
       (map? ctx)
        (set
         (keys ctx)))})))

(defn- q
  [ctx query]
  (biff.xtdb/q
   (query-context! ctx)
   query))

(defn- rows
  [descriptor ctx query]
  (mapv
   #(normalize-loaded-document
     descriptor
     ctx
     %)
   (q
    ctx
    query)))

