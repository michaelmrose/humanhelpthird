(defn- acceptance-error
  ([kind message]
   (acceptance-error kind message {}))
  ([kind message data]
   (ex-info
    message
    (merge
     {:error/type :net.humanhelp.example.chromium-acceptance/error
      :error/kind kind}
     data))))

(defn- consumer
  [f]
  (reify Consumer
    (accept [_ value]
      (f value))))

(defn- path-directories
  []
  (let [value (or (System/getenv "PATH") "")
        separator
        (re-pattern
         (java.util.regex.Pattern/quote File/pathSeparator))]
    (if (str/blank? value)
      []
      (str/split value separator -1))))

(defn- executable-path
  [value]
  (let [file (io/file (str value))]
    (when (and (.isFile ^File file)
               (.canExecute ^File file))
      (.toAbsolutePath (.toPath ^File file)))))

(defn- command-path
  [command]
  (some
   (fn [directory]
     (executable-path
      (io/file
       (if (str/blank? directory) "." directory)
       command)))
   (path-directories)))

(defn- chromium-executable
  []
  (let [override
        (or
         (some-> (System/getenv "HUMANHELP_CHROMIUM") str/trim not-empty)
         (some-> (System/getenv "GESSO_CHROMIUM") str/trim not-empty))]
    (if override
      (or
       (executable-path override)
       (command-path override)
       (throw
        (acceptance-error
         :invalid-chromium-override
         "Configured Chromium executable is unavailable."
         {:override override})))
      (or
       (some command-path chromium-candidates)
       (throw
        (acceptance-error
         :chromium-not-found
         "HumanHelp Chromium acceptance requires system Chromium/Chrome or HUMANHELP_CHROMIUM."
         {:checked chromium-candidates}))))))

(defn- available-port
  []
  (with-open [socket (ServerSocket. 0)]
    (.getLocalPort socket)))

(defn- uri-path
  [url]
  (.getPath (URI/create url)))

(defn- decode-form-component
  [value]
  (URLDecoder/decode
   (str (or value ""))
   (.name StandardCharsets/UTF_8)))

(defn- encoded-form-params
  [post-data]
  (into
   {}
   (map
    (fn [pair]
      (let [[k v]
            (str/split pair #"=" 2)]
        [(decode-form-component k)
         (decode-form-component v)])))
   (remove str/blank?
           (str/split (or post-data "") #"&"))))

(defn- eventually
  ([pred]
   (eventually 10000 pred))
  ([timeout-ms pred]
   (let [deadline (+ (System/currentTimeMillis) timeout-ms)]
     (loop []
       (let [value
             (try
               (pred)
               (catch Throwable _
                 nil))]
         (cond
           value
           value

           (< (System/currentTimeMillis) deadline)
           (do
             (Thread/sleep 25)
             (recur))

           :else
           nil))))))

