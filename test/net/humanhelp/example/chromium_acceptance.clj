(defn- start-runtime!
  []
  (let [port
        (available-port)

        base-url
        (str "http://127.0.0.1:" port)

        node
        (xtn/start-node {})]
    (try
      (let [application-assembly
            (humanhelp/require-application-assembly!)

            initial-system
            (merge
             humanhelp/initial-system
             {:biff.xtdb/node node
              :biff.ring/host "127.0.0.1"
              :biff.ring/port port
              :biff.ring/base-url base-url
              :biff.ring/secure false
              :biff.ring/ssl-redirect false
              :biff.ring/fallback-session-store
              (session.memory/memory-store)
              :biff.core/stop
              [(fn []
                 (.close node))]})

            system
            (application-preflight/start-biff-application!
             application-assembly
             initial-system
             #'humanhelp/modules
             [humanhelp/use-gesso-live
              humanhelp/use-aleph])]
        {:system system
         :base-url base-url})
      (catch Throwable error
        (try
          (.close node)
          (catch Throwable _))
        (throw error)))))

(defn- stop-runtime!
  [{:keys [system]}]
  (when system
    (biff.core/stop system))
  nil)

