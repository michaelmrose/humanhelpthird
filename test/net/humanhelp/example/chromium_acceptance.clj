(ns net.humanhelp.example.chromium-acceptance
  "Real Chromium acceptance for the production-model-backed HumanHelp example app.

   This namespace is intentionally *not* named ...-test. Ordinary JVM tests must
   remain independent of Chromium and of the generated browser artifact. The
   browser gate invokes -main explicitly after building the exact HumanHelp
   gesso-live.js artifact.

   The first scenario is the Request Claim -> Unclaim round trip and deliberately
   crosses the real joins that the preflight recovery work is meant to protect:

     real HumanHelp Ring middleware / session
       -> real /app render
       -> generated HumanHelp Gesso browser artifact
       -> real HTMX request construction
       -> browser-generated protocol-v3 command
       -> real Claim route
       -> production Request Choreo/model commit
       -> settlement + authoritative reacquisition
       -> persisted claimed reload
       -> real rendered Unclaim control
       -> second browser-generated protocol-v3 command
       -> real Unclaim route
       -> production Request Choreo/model commit
       -> settlement + authoritative reacquisition
       -> persisted open reload

   The test seeds only authoritative prerequisite data (Users, helper authority,
   and one open production Request). It never constructs, injects, or edits
   __gesso_live_optimistic_command. Both lifecycle commands observed on the wire
   must have been generated by the browser runtime itself."
