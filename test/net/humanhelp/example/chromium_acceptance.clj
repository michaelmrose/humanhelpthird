(deftest real-rendered-claim-crosses-browser-runtime-and-persists-test
  (let [runtime
        (start-runtime!)]
    (try
      (let [{:keys [system base-url]}
            runtime

            {:keys [request]}
            (seed-scenario! system)

            request-id
            (request/request-id request)

            browser
            (start-browser!)

            browser-context
            (new-browser-context! browser)]
        (try
          (let [^BrowserContext context
                (:context browser-context)

                ^Page page
                (.newPage context)]
            (with-redefs-fn
              {generate-code-var
               (fn [_length]
                 auth-code)}
              (fn []
                (sign-in! page base-url)

                (let [claim-button
                      (.locator page (claim-button-selector request-id))

                      encoded-rendered-action
                      (.getAttribute
                       claim-button
                       "data-gesso-live-optimistic")

                      rendered-action
                      (some-> encoded-rendered-action edn/read-string)

                      initial-observed-basis
                      (:observed-basis rendered-action)

                      fragment-request-start
                      (count
                       (:request-list-fragment-requests
                        @(:diagnostics browser-context)))

                      fragment-response-start
                      (count
                       (:request-list-fragment-responses
                        @(:diagnostics browser-context)))]
                  (testing "the authoritative initial /app render exposes a real semantic Claim control"
                    (is (= 1
                           (.count claim-button)))
                    (is (= :open
                           (request/status
                            (request/require-request system request-id)))))

                  (testing "the server render carries semantic action data but no browser-owned correlation identity"
                    (is (string? encoded-rendered-action))
                    (is (= request.choreo/claim-operation
                           (:operation rendered-action)))
                    (is (= {:request-id request-id}
                           (:arguments rendered-action)))
                    (is (some? (:observed-basis rendered-action)))
                    (is (not (contains? rendered-action :command-id)))
                    (is (not (contains? rendered-action :execution-id))))

                  (claim-through-browser! page request-id)

                  (testing "the browser, not the test, adds protocol-v3 correlation identity and preserves the rendered semantics"
                    (is
                     (eventually
                      default-timeout-ms
                      #(first (:claim-requests @(:diagnostics browser-context))))
                     (pr-str @(:diagnostics browser-context)))

                    (let [claim-request
                          (first (:claim-requests @(:diagnostics browser-context)))

                          params
                          (encoded-form-params (:post-data claim-request))

                          encoded-command
                          (get params example.app/optimistic-command-param)

                          command
                          (some-> encoded-command
                                  edn/read-string
                                  optimistic.protocol/wire->command)]
                      (is (string? encoded-command)
                          "The real HTMX POST must contain the browser-generated optimistic command parameter.")
                      (is (= (:operation rendered-action)
                             (:operation command)))
                      (is (= (:arguments rendered-action)
                             (:arguments command)))
                      (is (= (:observed-basis rendered-action)
                             (:observed-basis command)))
                      (is (= (:scope rendered-action)
                             (:scope command)))
                      (is (= (:fact-versions rendered-action)
                             (:fact-versions command)))
                      (is (some? (:command-id command)))
                      (is (some? (:execution-id command)))))

                (testing "the real server path commits Claim authoritatively"
                  (is (some?
                       (wait-for-authoritative-claim!
                        system
                        request-id))
                      (pr-str @(:diagnostics browser-context)))
                  (is
                   (eventually
                    default-timeout-ms
                    #(some
                      (fn [{:keys [status]}]
                        (when (< status 400) status))
                      (:claim-responses @(:diagnostics browser-context))))
                   (pr-str @(:diagnostics browser-context))))

                (testing "settlement/reacquisition performs a progression-bearing authoritative Request-list reread"
                  (is
                   (eventually
                    default-timeout-ms
                    #(progression-bearing-request-list-refresh
                      (:diagnostics browser-context)
                      fragment-request-start))
                   (pr-str @(:diagnostics browser-context)))
                  (is
                   (eventually
                    default-timeout-ms
                    #(successful-request-list-response-after?
                      (:diagnostics browser-context)
                      fragment-response-start))
                   (pr-str @(:diagnostics browser-context))))

                (testing "canonical reread replaces provisional ownership with a newer authoritative Claim frontier"
                  (let [unclaim-button
                        (wait-for-claimed-dom! page request-id)

                        request-card
                        (.locator page (request-card-selector request-id))

                        refresh-request
                        (progression-bearing-request-list-refresh
                         (:diagnostics browser-context)
                         fragment-request-start)

                        required-basis
                        (some-> refresh-request
                                :progression
                                xtdb-live/strongest-required-basis)

                        unclaim-action
                        (decode-rendered-action unclaim-button)

                        canonical-basis
                        (:observed-basis unclaim-action)]
                    (is (some? unclaim-button)
                        (pr-str @(:diagnostics browser-context)))
                    (is (nil?
                         (.getAttribute
                          request-card
                          "data-gesso-optimistic-provisional"))
                        "Canonical Request-list replacement must retire Gesso provisional ownership.")
                    (is (= request.choreo/unclaim-operation
                           (:operation unclaim-action)))
                    (is (some? required-basis)
                        (pr-str refresh-request))
                    (is (some? canonical-basis)
                        (pr-str unclaim-action))
                    (is (and
                         (some? required-basis)
                         (some? canonical-basis)
                         (not
                          (pos?
                           (xtdb-live/compare-bases
                            required-basis
                            canonical-basis))))
                        "The canonical Unclaim affordance must be rendered from an authoritative frontier satisfying the Live-requested minimum.")
                    (is (and
                         (some? initial-observed-basis)
                         (some? canonical-basis)
                         (xtdb-live/basis-advances?
                          initial-observed-basis
                          canonical-basis))
                        "The post-Claim canonical basis must strictly advance the initial rendered Claim basis.")))

                (testing "reload reconstructs the claimed state from authority rather than provisional DOM"
                  (.reload page)
                  (is (some?
                       (wait-for-claimed-dom! page request-id)))
                  (is (= :claimed
                         (request/status
                          (request/require-request system request-id)))))

                (let [unclaim-button
                      (wait-for-claimed-dom! page request-id)

                      rendered-unclaim-action
                      (decode-rendered-action unclaim-button)

                      pre-unclaim-basis
                      (:observed-basis rendered-unclaim-action)

                      unclaim-fragment-request-start
                      (count
                       (:request-list-fragment-requests
                        @(:diagnostics browser-context)))

                      unclaim-fragment-response-start
                      (count
                       (:request-list-fragment-responses
                        @(:diagnostics browser-context)))]
                  (testing "the persisted authoritative reload exposes semantic Unclaim without browser-owned correlation identity"
                    (is (= request.choreo/unclaim-operation
                           (:operation rendered-unclaim-action)))
                    (is (= {:request-id request-id}
                           (:arguments rendered-unclaim-action)))
                    (is (some? pre-unclaim-basis))
                    (is (not (contains? rendered-unclaim-action :command-id)))
                    (is (not (contains? rendered-unclaim-action :execution-id))))

                  (unclaim-through-browser! page request-id)

                  (testing "the browser independently creates the protocol-v3 Unclaim command"
                    (is
                     (eventually
                      default-timeout-ms
                      #(first (:unclaim-requests @(:diagnostics browser-context))))
                     (pr-str @(:diagnostics browser-context)))

                    (let [unclaim-request
                          (first (:unclaim-requests @(:diagnostics browser-context)))

                          params
                          (encoded-form-params (:post-data unclaim-request))

                          encoded-command
                          (get params example.app/optimistic-command-param)

                          command
                          (some-> encoded-command
                                  edn/read-string
                                  optimistic.protocol/wire->command)]
                      (is (string? encoded-command)
                          "The real Unclaim POST must contain a browser-generated optimistic command parameter.")
                      (is (= (:operation rendered-unclaim-action)
                             (:operation command)))
                      (is (= (:arguments rendered-unclaim-action)
                             (:arguments command)))
                      (is (= (:observed-basis rendered-unclaim-action)
                             (:observed-basis command)))
                      (is (= (:scope rendered-unclaim-action)
                             (:scope command)))
                      (is (= (:fact-versions rendered-unclaim-action)
                             (:fact-versions command)))
                      (is (some? (:command-id command)))
                      (is (some? (:execution-id command)))))

                  (testing "the real server path commits Unclaim authoritatively"
                    (is (some?
                         (wait-for-authoritative-unclaim!
                          system
                          request-id))
                        (pr-str @(:diagnostics browser-context)))
                    (is
                     (eventually
                      default-timeout-ms
                      #(some
                        (fn [{:keys [status]}]
                          (when (< status 400) status))
                        (:unclaim-responses @(:diagnostics browser-context))))
                     (pr-str @(:diagnostics browser-context))))

                  (testing "Unclaim settlement performs a progression-bearing authoritative Request-list reread"
                    (is
                     (eventually
                      default-timeout-ms
                      #(progression-bearing-request-list-refresh
                        (:diagnostics browser-context)
                        unclaim-fragment-request-start))
                     (pr-str @(:diagnostics browser-context)))
                    (is
                     (eventually
                      default-timeout-ms
                      #(successful-request-list-response-after?
                        (:diagnostics browser-context)
                        unclaim-fragment-response-start))
                     (pr-str @(:diagnostics browser-context))))

                  (testing "canonical Unclaim reread returns the Request to an authoritative open frontier"
                    (let [claim-button
                          (wait-for-open-dom! page request-id)

                          request-card
                          (.locator page (request-card-selector request-id))

                          refresh-request
                          (progression-bearing-request-list-refresh
                           (:diagnostics browser-context)
                           unclaim-fragment-request-start)

                          required-basis
                          (some-> refresh-request
                                  :progression
                                  xtdb-live/strongest-required-basis)

                          claim-action
                          (decode-rendered-action claim-button)

                          canonical-open-basis
                          (:observed-basis claim-action)]
                      (is (some? claim-button)
                          (pr-str @(:diagnostics browser-context)))
                      (is (nil?
                           (.getAttribute
                            request-card
                            "data-gesso-optimistic-provisional"))
                          "Canonical Request-list replacement must retire Unclaim provisional ownership.")
                      (is (= request.choreo/claim-operation
                             (:operation claim-action)))
                      (is (some? required-basis)
                          (pr-str refresh-request))
                      (is (some? canonical-open-basis)
                          (pr-str claim-action))
                      (is (and
                           (some? required-basis)
                           (some? canonical-open-basis)
                           (not
                            (pos?
                             (xtdb-live/compare-bases
                              required-basis
                              canonical-open-basis))))
                          "The canonical Claim affordance after Unclaim must satisfy the Live-requested minimum.")
                      (is (and
                           (some? pre-unclaim-basis)
                           (some? canonical-open-basis)
                           (xtdb-live/basis-advances?
                            pre-unclaim-basis
                            canonical-open-basis))
                          "The post-Unclaim canonical basis must strictly advance the authoritative Unclaim render basis.")))

                  (testing "reload reconstructs the open state after Unclaim from persisted authority"
                    (.reload page)
                    (is (some?
                         (wait-for-open-dom! page request-id)))
                    (is (= :open
                           (request/status
                            (request/require-request system request-id))))))

                (testing "no browser/page/network failure is hidden behind the green lifecycle"
                  (is (clean-browser-diagnostics?
                       @(:diagnostics browser-context))
                      (pr-str @(:diagnostics browser-context))))))))
          (finally
            (close-browser-context! browser-context)
            (stop-browser! browser))))
      (finally
        (stop-runtime! runtime)))))

