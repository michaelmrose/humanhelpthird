(defn- sign-in!
  [^Page page base-url]
  (.navigate page (str base-url "/"))

  (let [phone-input
        (.locator page "#phone-display")]
    (.waitFor phone-input)
    (.fill phone-input helper-phone)
    (.click
     (.locator
      page
      "#phone-auth-send-form button[type=\"submit\"]")))

  (let [code-input
        (.locator page "#code")]
    (.waitFor code-input)
    (.fill code-input auth-code)
    (.click
     (.locator
      page
      "#phone-auth-verify-form button[type=\"submit\"]")))

  (.waitForURL
   page
   (reify java.util.function.Predicate
     (test [_ url]
       (= "/app" (uri-path url)))))

  page)

