(defn- start-browser!
  []
  (let [chromium-path
        (chromium-executable)

        create-options
        (doto (Playwright$CreateOptions.)
          (.setEnv
           (assoc
            (into {} (System/getenv))
            "PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD"
            "1")))

        playwright
        (Playwright/create create-options)]
    (try
      (let [launch-options
            (doto (BrowserType$LaunchOptions.)
              (.setExecutablePath chromium-path)
              (.setHeadless true)
              (.setTimeout 20000.0))

            browser
            (.launch (.chromium playwright) launch-options)]
        {:playwright playwright
         :browser browser
         :chromium-executable chromium-path})
      (catch Throwable error
        (.close playwright)
        (throw error)))))

(defn- stop-browser!
  [{:keys [^Browser browser ^Playwright playwright]}]
  (when browser
    (.close browser))
  (when playwright
    (.close playwright))
  nil)

(defn- resource-text
  [candidates]
  (some-> (some io/resource candidates)
          slurp))

(defn- fulfill!
  [^Route route content-type body]
  (.fulfill
   route
   (doto (Route$FulfillOptions.)
     (.setStatus 200)
     (.setContentType content-type)
     (.setBody body))))

(defn- install-local-browser-assets!
  "Use pinned local HTMX/SSE bytes when the browser-test classpath supplies
   them (for example in Gesso's development/test environment). When unavailable,
   leave the application's real CDN request untouched instead of silently
   substituting a different implementation."
  [^BrowserContext context]
  (when-let [htmx (resource-text htmx-resource-candidates)]
    (.route
     context
     htmx-url
     (consumer
      #(fulfill! % "text/javascript; charset=utf-8" htmx))))

  (when-let [sse (resource-text sse-resource-candidates)]
    (.route
     context
     sse-url
     (consumer
      #(fulfill! % "text/javascript; charset=utf-8" sse))))

  ;; These assets are presentation/optional behavior outside the Claim protocol
  ;; being accepted here. Keep the real URLs in application markup, but make the
  ;; headless test independent of unrelated CDN availability.
  (.route
   context
   "https://cdn.jsdelivr.net/npm/basecoat-css@0.3.11/dist/basecoat.cdn.min.css"
   (consumer #(fulfill! % "text/css; charset=utf-8" "")))

  (.route
   context
   "https://cdn.jsdelivr.net/npm/basecoat-css@0.3.11/dist/js/all.min.js"
   (consumer #(fulfill! % "text/javascript; charset=utf-8" "")))

  (.route
   context
   "https://unpkg.com/htmx-ext-ws@2.0.2/ws.js"
   (consumer #(fulfill! % "text/javascript; charset=utf-8" "")))

  (.route
   context
   "https://unpkg.com/hyperscript.org@0.9.14"
   (consumer #(fulfill! % "text/javascript; charset=utf-8" "")))

  (.route
   context
   "https://fonts.googleapis.com/**"
   (consumer #(fulfill! % "text/css; charset=utf-8" "")))

  context)

(defn- new-browser-context!
  [{:keys [^Browser browser]}]
  (let [context
        (.newContext browser)

        diagnostics
        (atom
         {:console-errors []
          :web-errors []
          :request-failures []
          :claim-requests []
          :claim-responses []
          :unclaim-requests []
          :unclaim-responses []
          :mark-on-the-way-requests []
          :mark-on-the-way-responses []
          :complete-requests []
          :complete-responses []
          :cancel-requests []
          :cancel-responses []
          :reassign-requests []
          :reassign-responses []
          :request-list-fragment-requests []
          :request-list-fragment-responses []})]

    (.setDefaultTimeout context (double default-timeout-ms))
    (.setDefaultNavigationTimeout context (double default-timeout-ms))

    (.onConsoleMessage
     context
     (consumer
      (fn [^ConsoleMessage message]
        (when (#{"error" "assert"} (.type message))
          (swap!
           diagnostics
           update
           :console-errors
           conj
           {:type (.type message)
            :text (.text message)})))))

    (.onWebError
     context
     (consumer
      (fn [^WebError error]
        (swap!
         diagnostics
         update
         :web-errors
         conj
         {:error (.error error)}))))

    (.onRequestFailed
     context
     (consumer
      (fn [^Request request]
        (swap!
         diagnostics
         update
         :request-failures
         conj
         {:method (.method request)
          :url (.url request)
          :failure (.failure request)}))))

    (.onRequest
     context
     (consumer
      (fn [^Request request]
        (when (and
               (= "POST" (.method request))
               (str/ends-with? (uri-path (.url request)) "/claim"))
          (swap!
           diagnostics
           update
           :claim-requests
           conj
           {:url (.url request)
            :post-data (.postData request)}))

        (when (and
               (= "POST" (.method request))
               (str/ends-with? (uri-path (.url request)) "/unclaim"))
          (swap!
           diagnostics
           update
           :unclaim-requests
           conj
           {:url (.url request)
            :post-data (.postData request)}))

        (when (and
               (= "POST" (.method request))
               (str/ends-with? (uri-path (.url request)) "/mark-on-the-way"))
          (swap!
           diagnostics
           update
           :mark-on-the-way-requests
           conj
           {:url (.url request)
            :post-data (.postData request)}))

        (when (and
               (= "POST" (.method request))
               (str/ends-with? (uri-path (.url request)) "/complete"))
          (swap!
           diagnostics
           update
           :complete-requests
           conj
           {:url (.url request)
            :post-data (.postData request)}))

        (when (and
               (= "POST" (.method request))
               (str/ends-with? (uri-path (.url request)) "/cancel"))
          (swap!
           diagnostics
           update
           :cancel-requests
           conj
           {:url (.url request)
            :post-data (.postData request)}))

        (when (and
               (= "POST" (.method request))
               (str/ends-with? (uri-path (.url request)) "/reassign"))
          (swap!
           diagnostics
           update
           :reassign-requests
           conj
           {:url (.url request)
            :post-data (.postData request)}))

        (when (and
               (= "GET" (.method request))
               (= (routes/request-list-fragment-url)
                  (uri-path (.url request))))
          (swap!
           diagnostics
           update
           :request-list-fragment-requests
           conj
           {:url (.url request)
            :headers (into {} (.allHeaders request))})))))

    (.onResponse
     context
     (consumer
      (fn [^Response response]
        (when (and
               (= "POST" (.method (.request response)))
               (str/ends-with? (uri-path (.url response)) "/claim"))
          (swap!
           diagnostics
           update
           :claim-responses
           conj
           {:url (.url response)
            :status (.status response)}))

        (when (and
               (= "POST" (.method (.request response)))
