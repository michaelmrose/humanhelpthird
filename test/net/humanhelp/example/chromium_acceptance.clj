          (swap!
           diagnostics
           update
           :unclaim-responses
           conj
           {:url (.url response)
            :status (.status response)}))

        (when (and
               (= "POST" (.method (.request response)))
               (str/ends-with? (uri-path (.url response)) "/mark-on-the-way"))
          (swap!
           diagnostics
           update
           :mark-on-the-way-responses
           conj
           {:url (.url response)
            :status (.status response)}))

        (when (and
