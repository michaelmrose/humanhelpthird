(ns net.humanhelp.example.chromium-acceptance
  "Real Chromium acceptance for the production-model-backed HumanHelp example app.

   This namespace is intentionally *not* named ...-test. Ordinary JVM tests must
   remain independent of Chromium and of the generated browser artifact. The
   browser gate invokes -main explicitly after building the exact HumanHelp
   gesso-live.js artifact.

   The current scenario covers the Request Claim -> Unclaim -> Claim -> On-the-way -> Complete trajectory plus independent owner Cancel and manager Reassign trajectories and deliberately
   crosses the real joins that the preflight recovery work is meant to protect:

     real HumanHelp Ring middleware / session
       -> real /app render
       -> generated HumanHelp Gesso browser artifact
       -> real HTMX request construction
       -> browser-generated protocol-v3 command
       -> real Claim route
       -> production Request Choreo/model commit
       -> settlement + authoritative reacquisition
       -> persisted claimed reload
       -> real rendered Unclaim control
       -> second browser-generated protocol-v3 command
       -> real Unclaim route
      -> real Claim route again
      -> real Mark-on-the-way route
      -> real Complete route
       -> production Request Choreo/model commits
       -> settlement + authoritative reacquisition
       -> persisted terminal reload
       -> independent owner Cancel route
       -> authoritative cancelled reload
       -> independent manager Reassign route selected through the real target-helper dropdown
       -> authoritative reassignment + persisted reload

   The test seeds only authoritative prerequisite data (Users, helper/manager authority,
   one target helper, one requestor-owned open production Request, one helper-owned open Request for owner cancellation, and one additional open Request for reassignment). It never constructs, injects, or edits
   __gesso_live_optimistic_command. Every lifecycle command observed on the wire
   must have been generated by the browser runtime itself."
